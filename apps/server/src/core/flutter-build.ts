import { spawn } from "node:child_process";
import { mkdir, readFile, rm, stat } from "node:fs/promises";
import path from "node:path";
import { resourcePool } from './resources.js';

import { writeTextFile } from "./file-io.js";

type FlutterProjectFilesInput = {
  designName: string;
  mainDart: string;
  overwrite?: boolean;
  projectDir: string;
};

type BuildFlutterWebInput = {
  outputDir: string;
  projectDir: string;
  signal?: AbortSignal;
};

type PublishFlutterWebEntryInput = {
  outputDir: string;
  renderEntryPath: string;
};

const sanitizeFlutterPackageName = (value: string) => {
  const normalized = value
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9_]+/g, "_")
    .replace(/^_+|_+$/g, "");
  const stem = normalized || "design_output";
  const prefixed = /^[a-z]/.test(stem) ? stem : `design_${stem}`;
  const bounded = prefixed.slice(0, 55).replace(/_+$/, "") || "design_output";
  return `${bounded}_flutter`;
};

const escapeHtmlAttribute = (value: string) =>
  value
    .replaceAll("&", "&amp;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#39;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;");

const createFlutterPubspec = (designName: string) => `\
name: ${sanitizeFlutterPackageName(designName)}
description: Generated by svg-transform-core.
publish_to: none
version: 1.0.0+1

environment:
  sdk: ">=3.4.0 <4.0.0"

dependencies:
  flutter:
    sdk: flutter
  flutter_svg: ^2.0.10+1

flutter:
  uses-material-design: true
  assets:
    - assets/
`;

const createFlutterWebIndex = (designName: string) => `\
<!DOCTYPE html>
<html>
  <head>
    <base href="$FLUTTER_BASE_HREF" />
    <meta charset="UTF-8" />
    <meta content="IE=Edge" http-equiv="X-UA-Compatible" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
    <meta name="description" content="${escapeHtmlAttribute(designName)}" />
    <title>${escapeHtmlAttribute(designName)}</title>
  </head>
  <body>
    <script src="flutter_bootstrap.js" async></script>
  </body>
</html>
`;

const fileExists = async (filePath: string) => {
  try {
    await stat(filePath);
    return true;
  } catch {
    return false;
  }
};

const writeIfMissing = async ({
  content,
  filePath,
  overwrite,
}: {
  content: string;
  filePath: string;
  overwrite: boolean;
}) => {
  if (!overwrite && (await fileExists(filePath))) return;
  await writeTextFile(filePath, content);
};

const writeFlutterProjectFiles = async ({
  designName,
  mainDart,
  overwrite = false,
  projectDir,
}: FlutterProjectFilesInput) => {
  const libDir = path.join(projectDir, "lib");
  const webDir = path.join(projectDir, "web");
  const assetsDir = path.join(projectDir, "assets");
  await Promise.all([
    mkdir(libDir, { recursive: true }),
    mkdir(webDir, { recursive: true }),
    mkdir(assetsDir, { recursive: true }),
  ]);
  await Promise.all([
    writeIfMissing({
      content: mainDart,
      filePath: path.join(libDir, "main.dart"),
      overwrite,
    }),
    writeIfMissing({
      content: createFlutterPubspec(designName),
      filePath: path.join(projectDir, "pubspec.yaml"),
      overwrite,
    }),
    writeIfMissing({
      content: createFlutterWebIndex(designName),
      filePath: path.join(webDir, "index.html"),
      overwrite,
    }),
  ]);
};

const resolveFlutterBinary = () => process.env.FLUTTER_BIN?.trim() || "flutter";

const runFlutterCommand = async ({
  args,
  projectDir,
  signal,
}: {
  args: string[];
  projectDir: string;
  signal?: AbortSignal;
}) =>
  new Promise<void>((resolve, reject) => {
    const flutterBinary = resolveFlutterBinary();
    const child = spawn(flutterBinary, args, {
      cwd: projectDir,
      env: {
        ...process.env,
        CI: "true",
        FLUTTER_SUPPRESS_ANALYTICS: "true",
      },
      stdio: ["ignore", "pipe", "pipe"],
    });
    let stdout = "";
    let stderr = "";
    const append = (current: string, chunk: Buffer) =>
      `${current}${chunk.toString("utf8")}`.slice(-16_000);
    child.stdout.on("data", (chunk: Buffer) => {
      stdout = append(stdout, chunk);
    });
    child.stderr.on("data", (chunk: Buffer) => {
      stderr = append(stderr, chunk);
    });

    const abort = () => child.kill("SIGTERM");
    signal?.addEventListener("abort", abort, { once: true });
    child.once("error", (error: NodeJS.ErrnoException) => {
      signal?.removeEventListener("abort", abort);
      if (error.code === "ENOENT") {
        reject(
          new Error(
            `Flutter SDK not found. Install Flutter or set FLUTTER_BIN to the flutter executable (resolved: ${flutterBinary}).`,
          ),
        );
        return;
      }
      reject(error);
    });
    child.once("close", (code, closeSignal) => {
      signal?.removeEventListener("abort", abort);
      if (signal?.aborted) {
        reject(new Error("Flutter web build aborted"));
        return;
      }
      if (code === 0) {
        resolve();
        return;
      }
      const detail = [stderr.trim(), stdout.trim()].filter(Boolean).join("\n");
      reject(
        new Error(
          `Flutter web build failed (exit ${String(code)}, signal ${String(closeSignal ?? "none")})${detail ? `:\n${detail}` : ""}`,
        ),
      );
    });
  });

const buildFlutterWeb = async ({
  outputDir,
  projectDir,
  signal,
}: BuildFlutterWebInput) => {
  if (signal?.aborted) throw new Error("Flutter web build aborted");
  await rm(outputDir, { force: true, recursive: true });
  await mkdir(path.dirname(outputDir), { recursive: true });
  await resourcePool('build').run(() => runFlutterCommand({
    args: [
      "build",
      "web",
      "--release",
      "--base-href",
      "/",
      "--output",
      outputDir,
    ],
    projectDir,
    signal,
  }), signal);
  return path.join(outputDir, "index.html");
};

const toRelativeBaseHref = (renderEntryPath: string, outputDir: string) => {
  let relative = path
    .relative(path.dirname(renderEntryPath), outputDir)
    .replaceAll(path.sep, "/");
  if (!relative.startsWith(".")) relative = `./${relative}`;
  return `${relative.replace(/\/+$/, "")}/`;
};

const publishFlutterWebEntry = async ({
  outputDir,
  renderEntryPath,
}: PublishFlutterWebEntryInput) => {
  const builtIndexPath = path.join(outputDir, "index.html");
  const builtIndex = await readFile(builtIndexPath, "utf8");
  const baseHref = toRelativeBaseHref(renderEntryPath, outputDir);
  const nextIndex = /<base\b[^>]*>/i.test(builtIndex)
    ? builtIndex.replace(/<base\b[^>]*>/i, `<base href="${baseHref}" />`)
    : builtIndex.replace(/<head\b[^>]*>/i, (tag) => `${tag}\n    <base href="${baseHref}" />`);
  await writeTextFile(renderEntryPath, nextIndex);
  return renderEntryPath;
};

export {
  buildFlutterWeb,
  publishFlutterWebEntry,
  writeFlutterProjectFiles,
};
